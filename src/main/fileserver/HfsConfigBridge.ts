import type { FileServerSettings, UserAccount, VfsNode } from '@shared/fileserver';

export interface GenerateConfigOptions {
  settings: FileServerSettings;
  users?: UserAccount[];
  vfs?: VfsNode[];
  internalToken?: string;
  adminPassword?: string;
}

export const DEFAULT_PLUGINS = [
  'antibrute',
  'download-counter',
  'server-info',
  'list-uploader',
  'share-links',
  'sharp',
  'thumbnails',
  'chat-plus',
  'auto-refresh',
  'password-rules',
  'video-player',
  'mini-player',
  'url-shortener',
  'show-any',
  'tls-tunnel',
  'trashbin',
  'copy-files',
  'Hide-file',
  'shared',
];

export const DEFAULT_PLUGINS_CONFIG_YAML = `plugins_config:
  share-links:
    onlyFor:
      - smaran
  thumbnails:
    log: true
    videos: true
  chat-plus:
    anonWrite: true
    anonRead: true
  password-rules:
    minLength: 4
  url-shortener:
    linkPrefix: /smaran
    managementAPI: true
    linkSlashAllowed: true
    linkEditAllowed: true
  copy-files:
    onlyFor:
      - admistrators
      - smaran
  Hide-file:
    hideFiles: ""
    hideExactFiles: ""
    hideFolders: ""
  trashbin:
    trashbin_verboseLogging: true`;

export function generateHfsConfigYaml(options: GenerateConfigOptions): string {
  const { settings, users = [], vfs = [], adminPassword } = options;
  const lines: string[] = [];

  lines.push('# Generated by Smaran HFS Bridge');
  lines.push(`title: "Smaran HFS"`);
  lines.push(`port: ${settings.port || 5901}`);
  lines.push(`localhost_admin: false`);
  lines.push(`force_theme: "dark"`);
  lines.push(`open_browser: false`);
  lines.push(`accept_cors: true`);

  const accounts = [...users];
  if (accounts.length === 0) {
    accounts.push({
      id: 'smaran',
      username: settings.adminUsername || 'smaran',
      password: adminPassword || settings.adminPassword || 'smaran',
      role: 'admin',
      isSystem: true,
    });
  }

  lines.push('accounts:');
  for (const acc of accounts) {
    lines.push(`  ${acc.username}:`);
    const pwd =
      acc.username === (settings.adminUsername || 'smaran') && adminPassword
        ? adminPassword
        : acc.password || 'smaran';
    lines.push(`    password: "${pwd}"`);
    if (acc.role === 'admin') {
      lines.push('    admin: true');
      lines.push('    ignore_limits: true');
      lines.push('    belongs:');
      lines.push('      - admistrators');
    }
  }
  lines.push('  admistrators:');
  lines.push('    ignore_limits: true');
  lines.push('    admin: true');

  lines.push('vfs:');
  if (vfs.length > 0) {
    for (const node of vfs) {
      if (node.physicalPath) {
        const cleanPath = node.physicalPath.replace(/\\/g, '/');
        const vfsRel = node.vfsPath.replace(/^\//, '') || node.name;
        lines.push(`  ${vfsRel}:`);
        lines.push(`    source: "${cleanPath}"`);
      }
    }
  } else if (settings.rootDir) {
    const cleanRoot = settings.rootDir.replace(/\\/g, '/');
    lines.push(`  source: "${cleanRoot}"`);
    lines.push('  can_see: "*"');
    lines.push('  can_read: "*"');
    lines.push('  can_list: "*"');
  }

  lines.push('enable_plugins:');
  for (const p of DEFAULT_PLUGINS) {
    lines.push(`  - ${p}`);
  }

  lines.push(DEFAULT_PLUGINS_CONFIG_YAML);

  return lines.join('\n') + '\n';
}
