import type { FileServerSettings, UserAccount, VfsNode } from '@shared/fileserver';

export interface GenerateConfigOptions {
  settings: FileServerSettings;
  users?: UserAccount[];
  vfs?: VfsNode[];
  internalToken?: string;
  adminPassword?: string;
}

export function generateHfsConfigYaml(options: GenerateConfigOptions): string {
  const { settings, users = [], vfs = [], adminPassword } = options;
  const lines: string[] = [];

  lines.push('# Generated by Smaran HFS Bridge');
  lines.push(`title: "Smaran HFS"`);
  lines.push(`port: ${settings.port}`);
  lines.push(`localhost_admin: false`);
  lines.push(`force_theme: "dark"`);
  lines.push(`open_browser: false`);
  lines.push(`accept_cors: true`);

  const accounts = [...users];
  if (accounts.length === 0) {
    accounts.push({
      id: 'admin',
      username: settings.adminUsername || 'admin',
      password: adminPassword || settings.adminPassword || 'smaran@123',
      role: 'admin',
      isSystem: true,
    });
  }

  lines.push('accounts:');
  for (const acc of accounts) {
    lines.push(`  ${acc.username}:`);
    const pwd =
      acc.username === (settings.adminUsername || 'admin') && adminPassword
        ? adminPassword
        : acc.password || 'smaran@123';
    lines.push(`    password: "${pwd}"`);
    if (acc.role === 'admin') {
      lines.push('    admin: true');
    }
  }

  lines.push('vfs:');
  if (vfs.length > 0) {
    for (const node of vfs) {
      if (node.physicalPath) {
        const cleanPath = node.physicalPath.replace(/\\/g, '/');
        const vfsRel = node.vfsPath.replace(/^\//, '') || node.name;
        lines.push(`  ${vfsRel}:`);
        lines.push(`    source: "${cleanPath}"`);
      }
    }
  } else if (settings.rootDir) {
    const cleanRoot = settings.rootDir.replace(/\\/g, '/');
    lines.push(`  source: "${cleanRoot}"`);
    lines.push('  can_see: "*"');
    lines.push('  can_read: "*"');
    lines.push('  can_list: "*"');
  }

  return lines.join('\n') + '\n';
}
