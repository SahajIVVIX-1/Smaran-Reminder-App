// Makes Smaran's license signing key pair, once, on the publisher's own PC.
//
//   node scripts/license-keygen.mjs
//
// The private key goes to %USERPROFILE%\.smaran-license\private-key.json, outside the project, and
// is never overwritten. Back it up somewhere safe: without it no new licenses can be issued, and
// anyone who has it can issue them. The public key is written into
// src/shared/license/publicKey.ts so the app can check licenses; rebuild Smaran afterwards.
// Running it again when a key already exists only re-syncs the public key from it.

import { generateKeyPairSync } from 'node:crypto';
import * as fs from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const KEY_DIR = process.env.SMARAN_LICENSE_KEY_DIR || join(homedir(), '.smaran-license');
const keyFile = join(KEY_DIR, 'private-key.json');
const publicFile = join(root, 'src', 'shared', 'license', 'publicKey.ts');

let jwk;
if (fs.existsSync(keyFile)) {
  jwk = JSON.parse(fs.readFileSync(keyFile, 'utf8'));
  if (jwk.kty !== 'OKP' || jwk.crv !== 'Ed25519' || !jwk.x || !jwk.d)
    throw new Error(`${keyFile} is not an Ed25519 private key.`);
  console.log(`Using the existing key in ${keyFile} (it is never replaced).`);
} else {
  const { privateKey } = generateKeyPairSync('ed25519');
  jwk = { ...privateKey.export({ format: 'jwk' }), use: 'sig', product: 'smaran.sahaj.si' };
  fs.mkdirSync(KEY_DIR, { recursive: true });
  fs.writeFileSync(keyFile, `${JSON.stringify(jwk, null, 2)}\n`, { encoding: 'utf8', flag: 'wx' });
  console.log(`New private key: ${keyFile}`);
  console.log('Back it up somewhere safe and never share it or commit it.');
}

fs.writeFileSync(
  publicFile,
  `// Generated by scripts/license-keygen.mjs. The Ed25519 public key licenses are checked with.\n` +
    `// The matching private key stays on the publisher's PC (never in this repository).\n` +
    `export const LICENSE_PUBLIC_KEY = '${jwk.x}';\n`,
  'utf8',
);
console.log(`Public key written to ${publicFile}`);
